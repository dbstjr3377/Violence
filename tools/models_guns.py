# 무늬 칠하기 도우미 ─────────────────────────────

def slots(period, width, axis="z", dark=(18, 18, 20), lo=-99, hi=99):
    """일정 간격의 홈(방열구, 세레이션)"""
    def p(face, pt, fu, fv):
        v = {"x": pt[0], "y": pt[1], "z": pt[2]}[axis]
        if lo <= v <= hi and (v % period) < width and face in ("east", "west", "up"):
            return dark
        return None
    return p


def engrave(text_rows, color=(220, 220, 225)):
    return None


def chain(*ps):
    def p(face, pt, fu, fv):
        for q in ps:
            c = q(face, pt, fu, fv)
            if c is not None:
                return c
        return None
    return p


def bore(face, pt, fu, fv, r=0.22):
    """총구 정면의 검은 구멍"""
    if face == "south" and (fu - 0.5) ** 2 + (fv - 0.5) ** 2 < r:
        return (8, 8, 8)
    return None


def bore_small(face, pt, fu, fv):
    return bore(face, pt, fu, fv, 0.12)


